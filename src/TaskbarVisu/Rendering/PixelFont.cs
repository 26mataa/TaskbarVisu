            var bits = new bool[GlyphHeight, w];
            for (int y = 0; y < GlyphHeight; y++)
                for (int x = 0; x < w; x++)
                    bits[y, x] = rows[y][x] == '#';
            result[ch] = new Glyph(w, bits);
        }
        return result;
    }

    private static Glyph? Get(char c)
    {
        // Les lettres accentuées utilisent la lettre de base (la matrice 5×7 n'a pas la place pour l'accent).
        c = char.ToUpperInvariant(c) switch
        {
            'É' or 'È' or 'Ê' or 'Ë' => 'E',
            'À' or 'Â' or 'Ä' or 'Á' => 'A',
            'Î' or 'Ï' or 'Í' => 'I',
            'Ô' or 'Ö' or 'Ó' => 'O',
            'Û' or 'Ü' or 'Ù' or 'Ú' => 'U',
            'Ç' => 'C',
            'Ñ' => 'N',
            var u => u,
        };
        return Glyphs.TryGetValue(c, out var g) ? g : Glyphs.GetValueOrDefault('*');
    }

    public static int Measure(string text, int pixel)
    {
        int w = 0;
        foreach (char c in text)
        {
            var g = Get(c);
            if (g is not null) w += (g.Width + 1) * pixel;
        }
        return Math.Max(0, w - pixel);
    }

    /// <summary>Dessine le texte avec son coin supérieur gauche en (x, top), alignés sur la grille de pixels.</summary>
    public static void Draw(SKCanvas canvas, string text, float x, float top, int pixel, SKPaint paint)
    {
        float cx = MathF.Round(x);
        float cy = MathF.Round(top);
        foreach (char c in text)
        {
            var g = Get(c);
            if (g is null) continue;
            for (int y = 0; y < GlyphHeight; y++)
            {
                int run = -1;
                for (int gx = 0; gx <= g.Width; gx++)
                {
                    bool on = gx < g.Width && g.Bits[y, gx];
                    if (on && run < 0) run = gx;
                    else if (!on && run >= 0)
                    {
                        // Les pixels contigus d'une ligne sont regroupés en un seul rectangle.
                        canvas.DrawRect(cx + run * pixel, cy + y * pixel, (gx - run) * pixel, pixel, paint);
                        run = -1;
                    }
                }
            }
            cx += (g.Width + 1) * pixel;
        }
    }
}
